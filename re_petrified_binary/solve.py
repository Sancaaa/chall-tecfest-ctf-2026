TARGET = b'\xd0\xb0\xb8\x3e\x0d\xf8\x4a\xac\x37\x91\xa9\x43\x57\xe5\x3e\xc9\x66\x2c\x07\x51'
BLOB = b'\x07\x06\x52\x75\x0b\x10\x47\x13\x7d\x4a\x1d\x54\x0a\x5b\x18\x1f\x5e\x03\x54\x03\x0c\x00\x01\x5f\x5a\x3c\x51\x12\x2d\x01\x1c\x54\x3b\x58\x5e\x1f\x55\x06\x48\x03\x37\x3c\x45\x5b\x5f\x10\x6c\x51\x3f\x43\x5a\x04\x57\x6f\x0e\x28\x00\x54\x5b\x6f\x62\x53\x6e\x51\x5f\x0f\x5f\x10\x7b\x5f\x31\x17\x07\x44\x10'
K1, K2 = 0x37, 0xC5

def ror8(v, n):
    return ((v >> n) | (v << (8 - n))) & 0xFF

formula = ""
for i, t in enumerate(TARGET):
    v = t ^ K2 ^ ((i * 0x1F) & 0xFF)
    v = ror8(v, i % 7 + 1)
    v = (v - K1) & 0xFF
    formula += chr(v)
print("formula:", formula)

flag = "".join(chr(b ^ ord(formula[i % 20])) for i, b in enumerate(BLOB))
print("flag   :", flag)